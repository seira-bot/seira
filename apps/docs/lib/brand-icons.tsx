const BRAND_ICONS: Record<string, ReactElement> = { AppleLogo, WindowsLogo, AndroidLogo };

function replaceBrandIcon<T extends { icon?: ReactNode }>(node: T): T {
  if (typeof node.icon === 'string' && node.icon in BRAND_ICONS) node.icon = BRAND_ICONS[node.icon];
  return node;
}

// fumadocs-core 16.14.5: lucideIconsPlugin resolves every string icon, so this plugin must run before it.
export function brandIconsPlugin(): LoaderPlugin {
  return {
    name: 'seira:brand-icons',
    transformPageTree: {
      file: replaceBrandIcon,
      folder: replaceBrandIcon,
      separator: replaceBrandIcon,
    },
  };
}
